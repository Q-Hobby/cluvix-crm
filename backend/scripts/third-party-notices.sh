#!/usr/bin/env bash
# Sinh THIRD_PARTY_NOTICES.txt cho bản phát hành backend: liệt kê MỌI Go module được biên dịch
# vào các binary (go list -deps của TẤT CẢ main package: server `.`, `cmd/*`, …) kèm nguyên văn file
# LICENSE/COPYING/NOTICE/… của nó, cộng mục Go standard library (runtime + stdlib được link tĩnh vào
# mọi binary Go). Cần khi phân phối binary: MIT/BSD yêu cầu kèm thông báo bản quyền, Apache-2.0 yêu
# cầu kèm NOTICE. Chỉ dùng go toolchain + module cache, không tải tool ngoài.
#
# Dùng: make third-party-notices   (hoặc: bash scripts/third-party-notices.sh [output])
#       make build-linux gọi script này để file đi kèm binary phát hành.
set -euo pipefail

cd "$(dirname "$0")/.."
OUT="${1:-THIRD_PARTY_NOTICES.txt}"

go mod download >/dev/null

MAIN_MODULE="$(go list -m)"

# Mọi main package của module (server + cmd/* + tool khác) — trước đây chỉ quét `.` nên module chỉ
# do cmd/migrate kéo vào (driver migrate…) bị bỏ sót khỏi bản thông báo.
MAIN_PKGS=()
while IFS= read -r pkg; do
  [ -n "$pkg" ] && MAIN_PKGS+=("$pkg")
done < <(go list -f '{{if eq .Name "main"}}{{.ImportPath}}{{end}}' ./...)
if [ "${#MAIN_PKGS[@]}" -eq 0 ]; then
  echo "ERROR: không tìm thấy main package nào" >&2
  exit 1
fi

# Hợp nhất module của mọi main package (sort -u), bỏ chính module của repo.
MODULES="$(go list -deps -f '{{with .Module}}{{.Path}}|{{.Version}}|{{.Dir}}{{end}}' "${MAIN_PKGS[@]}" \
  | grep -v '^$' | sort -u | grep -v "^${MAIN_MODULE}|" || true)"

GOROOT_DIR="$(go env GOROOT)"
GO_VERSION="$(go env GOVERSION)"

{
  echo "Third-party notices for ${MAIN_MODULE} (backend binaries)"
  echo "Generated by scripts/third-party-notices.sh — do not edit by hand."
  echo "Main packages scanned: ${MAIN_PKGS[*]}"
  echo
} > "$OUT"

missing=0
count=0

# emit_license_files <dir> — ghi mọi file license phổ biến ở gốc thư mục; trả 0 nếu có ít nhất 1.
emit_license_files() {
  local dir="$1" found=1 f
  for f in "$dir"/LICENSE* "$dir"/LICENCE* "$dir"/COPYING* "$dir"/COPYRIGHT* "$dir"/NOTICE* \
           "$dir"/UNLICENSE* "$dir"/license* "$dir"/License* "$dir"/copying* "$dir"/Copyright* \
           "$dir"/notice* "$dir"/unlicense*; do
    [ -f "$f" ] || continue
    found=0
    echo "--- $(basename "$f") ---" >> "$OUT"
    cat "$f" >> "$OUT"
    echo >> "$OUT"
  done
  return "$found"
}

# Go standard library + runtime — link tĩnh vào mọi binary (BSD-3-Clause, file LICENSE ở GOROOT).
count=$((count + 1))
{
  echo "================================================================================"
  echo "Go standard library (std) ${GO_VERSION}"
  echo "================================================================================"
} >> "$OUT"
# Bản phân phối chính thức để LICENSE ngay ở GOROOT; Homebrew dời nó lên thư mục cha của libexec.
GO_LICENSE=""
for cand in "${GOROOT_DIR}/LICENSE" "${GOROOT_DIR}/../LICENSE"; do
  if [ -f "$cand" ]; then GO_LICENSE="$cand"; break; fi
done
if [ -n "$GO_LICENSE" ]; then
  echo "--- LICENSE ---" >> "$OUT"
  cat "$GO_LICENSE" >> "$OUT"
  echo >> "$OUT"
  if [ -f "${GOROOT_DIR}/PATENTS" ]; then
    echo "--- PATENTS ---" >> "$OUT"
    cat "${GOROOT_DIR}/PATENTS" >> "$OUT"
    echo >> "$OUT"
  fi
else
  missing=$((missing + 1))
  echo "(GOROOT/LICENSE not found — see https://go.dev/LICENSE)" >> "$OUT"
  echo "WARN: no LICENSE at ${GOROOT_DIR}" >&2
fi
echo >> "$OUT"

while IFS='|' read -r path version dir; do
  [ -z "$path" ] && continue
  count=$((count + 1))
  {
    echo "================================================================================"
    echo "${path} ${version}"
    echo "================================================================================"
  } >> "$OUT"
  if ! emit_license_files "$dir"; then
    missing=$((missing + 1))
    echo "(no license file found at module root — check upstream: https://pkg.go.dev/${path})" >> "$OUT"
    echo "WARN: no license file for ${path} ${version}" >&2
  fi
  echo >> "$OUT"
done <<< "$MODULES"

echo "Wrote ${OUT}: ${count} entries (Go std + modules) from ${#MAIN_PKGS[@]} main packages, ${missing} without a license file." >&2
