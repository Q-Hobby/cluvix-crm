-- Tạo bảng `order_plan` (keep-set CRM). Idempotent: CREATE TABLE IF NOT EXISTS.
CREATE TABLE IF NOT EXISTS `order_plan` (
  `id` int NOT NULL AUTO_INCREMENT,
  `code` varchar(25) NOT NULL COMMENT 'Mã đơn hàng',
  `old_code` varchar(50) DEFAULT NULL COMMENT 'Mã đơn hàng cũ (sync đối tác)',
  `orderPlanType` tinyint DEFAULT '1' COMMENT 'Đơn hàng mới hay cũ',
  `customer_id` int NOT NULL COMMENT 'Khách hàng',
  `appointment_id` int DEFAULT NULL COMMENT 'Lịch hẹn',
  `branch_id` int DEFAULT NULL COMMENT 'Chi nhánh',
  `discount` decimal(20,2) DEFAULT '0.00' COMMENT 'Tổng giảm coupon',
  `discount_other` decimal(20,2) DEFAULT '0.00' COMMENT 'Giảm giá khác của đơn hàng',
  `paymentPlan` decimal(20,2) DEFAULT '0.00' COMMENT 'Tổng thanh toán cho đơn hàng',
  `debtsPlan` decimal(20,2) DEFAULT '0.00' COMMENT 'Công nợ đơn hàng',
  `listRevenues` json DEFAULT NULL COMMENT 'JSON array tư vấn viên phụ trách (1-nhiều)',
  `source_id` int DEFAULT NULL COMMENT 'Nguồn khách hàng',
  `status` tinyint(1) DEFAULT '1' COMMENT 'Trạng thái kế hoạch điều trị: 0 - lock, 1 - unlock, 2 - deleted, mặc định là 1',
  `created_time` bigint DEFAULT NULL COMMENT 'Ngày nhập đơn hàng',
  `note` text COMMENT 'Ghi chú',
  `created_at` bigint DEFAULT NULL COMMENT 'Thời gian tạo mới',
  `updated_at` bigint NOT NULL DEFAULT '0',
  `created_by` int DEFAULT NULL COMMENT 'Được tạo bởi ai',
  `updated_by` int DEFAULT NULL COMMENT 'Người cập nhật gần đây nhất',
  PRIMARY KEY (`id`),
  UNIQUE KEY `code` (`code`),
  KEY `fk-order_treatment_plan-branch_id` (`branch_id`),
  KEY `fk-order_treatment_plan-created_by` (`created_by`),
  KEY `fk-order_treatment_plan-customer_id` (`customer_id`),
  KEY `fk-order_treatment_plan-source_id` (`source_id`),
  KEY `fk-order_treatment_plan-updated_by` (`updated_by`),
  FULLTEXT KEY `ft_otp_note_ngram` (`note`) /*!50100 WITH PARSER `ngram` */ ,
  KEY `idx_order_plan_created_time_branch` (`created_time`,`branch_id`),
  KEY `fk-order_plan-appointment_id` (`appointment_id`),
  CONSTRAINT `fk-order_treatment_plan-branch_id` FOREIGN KEY (`branch_id`) REFERENCES `branch` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `fk-order_treatment_plan-customer_id` FOREIGN KEY (`customer_id`) REFERENCES `customer` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `fk-order_treatment_plan-source_id` FOREIGN KEY (`source_id`) REFERENCES `source` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `fk-order_plan-appointment_id` FOREIGN KEY (`appointment_id`) REFERENCES `appointment` (`id`) ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
