-- Tạo bảng `payment` (keep-set CRM). Idempotent: CREATE TABLE IF NOT EXISTS.
CREATE TABLE IF NOT EXISTS `payment` (
  `id` int NOT NULL AUTO_INCREMENT,
  `code` varchar(255) NOT NULL COMMENT 'Mã thanh toán',
  `old_code` varchar(50) DEFAULT NULL COMMENT 'Mã phiếu thu/chi cũ (sync đối tác)',
  `customer_id` int DEFAULT NULL COMMENT 'ID khách hàng',
  `parent_id` int DEFAULT NULL COMMENT 'Mã id của đơn hàng',
  `serviceUsed_id` int DEFAULT NULL COMMENT 'Thanh toán cho dịch vụ nào',
  `branch_id` int NOT NULL COMMENT 'Chi nhánh',
  `method` int NOT NULL COMMENT 'Hình thức thanh toán',
  `card_type_id` int DEFAULT NULL COMMENT 'Phương thức thanh toán',
  `bank_code` varchar(255) DEFAULT NULL COMMENT 'Mã hóa đơn ngân hàng',
  `payment_time` bigint DEFAULT NULL COMMENT 'Ngày thu tiền',
  `payment_of_date` bigint DEFAULT NULL COMMENT 'Ngày thanh toán',
  `amount` decimal(20,2) NOT NULL COMMENT 'Tổng tiền thanh toán',
  `amount_type` int DEFAULT NULL COMMENT 'Loại số tiền',
  `deposit_after` decimal(20,2) DEFAULT '0.00' COMMENT 'Tiền đặt cọc sau khi thanh toán',
  `deposit_id` int DEFAULT NULL COMMENT 'ID payment đặt cọc gốc (dùng khi chuyển cọc)',
  `deposit_type` tinyint DEFAULT '0' COMMENT 'Loại đặt cọc',
  `payment_for` smallint DEFAULT '0' COMMENT '1-Hoàn dịch vụ, 2-Hoàn cọc, 3-Đặt cọc, 4-Thanh toán, 5-Chuyển cọc, 6-Hoàn ký gửi, 7-Thu tiền phòng khám, 8-Chi tiền phòng khám',
  `note` text COMMENT 'Ghi chú',
  `created_at` bigint DEFAULT NULL COMMENT 'Thời gian tạo mới',
  `updated_at` bigint NOT NULL DEFAULT '0',
  `created_by` int DEFAULT NULL COMMENT 'Được tạo bởi ai',
  `updated_by` int DEFAULT NULL COMMENT 'Người cập nhật gần đây nhất',
  `appointment_id` int DEFAULT NULL COMMENT 'Lượt khám (FK → appointment)',
  `service_id_snapshot` int DEFAULT NULL COMMENT 'service_id cua order_service_used tai thoi diem payment nay phat sinh, NULL = chua tung doi dich vu',
  PRIMARY KEY (`id`),
  UNIQUE KEY `code` (`code`),
  KEY `fk-payment-branch_id` (`branch_id`),
  KEY `fk-payment-card_type_id-card_type-id` (`card_type_id`),
  KEY `fk-payment-created_by-user-id` (`created_by`),
  KEY `fk-payment-method` (`method`),
  KEY `fk-payment-parent_id-order_plan-id` (`parent_id`),
  KEY `fk-payment-updated_by-user-id` (`updated_by`),
  KEY `idx-payment-deposit_id` (`deposit_id`),
  KEY `idx-payment-payment_of_date` (`payment_of_date`),
  KEY `idx_payment_billing_agg` (`appointment_id`,`payment_for`,`amount`),
  KEY `idx_payment_time_cover` (`payment_time`,`payment_for`,`deposit_type`,`branch_id`,`amount`),
  KEY `idx_payment_customer` (`customer_id`),
  KEY `idx_payment_customer_for` (`customer_id`,`payment_for`),
  KEY `idx_payment_for` (`payment_for`),
  KEY `idx_payment_service_for` (`serviceUsed_id`,`payment_for`),
  CONSTRAINT `fk-payment-branch_id` FOREIGN KEY (`branch_id`) REFERENCES `branch` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `fk-payment-card_type_id-card_type-id` FOREIGN KEY (`card_type_id`) REFERENCES `card_type` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `fk-payment-customer_id` FOREIGN KEY (`customer_id`) REFERENCES `customer` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `fk-payment-deposit_id` FOREIGN KEY (`deposit_id`) REFERENCES `payment` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `fk-payment-method` FOREIGN KEY (`method`) REFERENCES `payment_method` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `fk-payment-parent_id-order_plan-id` FOREIGN KEY (`parent_id`) REFERENCES `order_plan` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `fk-payment-serviceUsed_id` FOREIGN KEY (`serviceUsed_id`) REFERENCES `order_service_used` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `fk-payment-appointment_id` FOREIGN KEY (`appointment_id`) REFERENCES `appointment` (`id`) ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
