-- Tạo bảng `appointment` (keep-set CRM). Idempotent: CREATE TABLE IF NOT EXISTS.
CREATE TABLE IF NOT EXISTS `appointment` (
  `id` int NOT NULL AUTO_INCREMENT,
  `code` varchar(25) NOT NULL COMMENT 'Mã code',
  `old_code` varchar(50) DEFAULT NULL COMMENT 'Mã lịch hẹn cũ (sync đối tác)',
  `customer_id` int DEFAULT NULL COMMENT 'Id Khách hàng',
  `appointment_type_id` int DEFAULT NULL COMMENT 'Loại lịch hẹn',
  `branch_id` int DEFAULT NULL COMMENT 'Chi nhánh',
  `appointment_date_first` bigint DEFAULT NULL COMMENT 'Thời gian hẹn lần đầu',
  `appointment_date` bigint DEFAULT NULL COMMENT 'Thời gian hẹn',
  `appointmentListDate` json DEFAULT NULL COMMENT 'Danh sách các ngày hẹn đã thay đổi',
  `schedule_time` int DEFAULT NULL COMMENT 'Thời gian dự kiến',
  `appointment_number` int DEFAULT NULL COMMENT 'Số lần hẹn',
  `checkin_date` bigint DEFAULT NULL COMMENT 'Thời gian khách đến',
  `sale_start` bigint DEFAULT NULL COMMENT 'Thời gian bắt đầu tư vấn',
  `sale_end` bigint DEFAULT NULL COMMENT 'Thời gian kết thúc tư vấn',
  `checkout_date` bigint DEFAULT NULL COMMENT 'Thời gian khách về',
  `content` text COMMENT 'Nội dung lịch hẹn',
  `contentPrivate` text COMMENT 'Nội dung lịch hẹn (Nội bộ)',
  `noteTimeline` json DEFAULT NULL COMMENT 'Timeline tương tác với lịch hẹn',
  `noteAppointment` text COMMENT 'Ghi chú lịch hẹn',
  `is_accepted` int DEFAULT NULL COMMENT 'Khách hàng đồng ý hay không',
  `confirmAppointment` tinyint DEFAULT '0' COMMENT 'Khách hàng đồng ý hay không',
  `type_service_id` int DEFAULT NULL COMMENT 'Nhóm dịch vụ quan tâm',
  `order_service_used_id` int DEFAULT NULL COMMENT 'Dịch vụ điều trị',
  `source_id` int DEFAULT NULL COMMENT 'Nguồn khách hàng theo lịch hẹn',
  `revenue_id` int DEFAULT NULL COMMENT 'Người tư vấn là ai',
  `convert_id` int DEFAULT NULL COMMENT 'Người chuyển đổi',
  `service_id` int DEFAULT NULL COMMENT 'Dịch vụ hẹn',
  `type_service_accepted_id` int DEFAULT NULL COMMENT 'Nhóm dịch vụ đồng ý',
  `appointment_reason_id` int DEFAULT NULL COMMENT 'Lý do',
  `bookType` tinyint DEFAULT NULL COMMENT 'Phân loại',
  `status` tinyint(1) DEFAULT '1',
  `created_at` bigint DEFAULT NULL,
  `updated_at` bigint NOT NULL DEFAULT '0',
  `created_by` int DEFAULT NULL,
  `updated_by` int DEFAULT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `code` (`code`),
  KEY `fk-appointment-appointment_reason_id` (`appointment_reason_id`),
  KEY `fk-appointment-convert_id` (`convert_id`),
  KEY `fk-appointment-order_service_used_id` (`order_service_used_id`),
  KEY `fk-appointment-revenue_id` (`revenue_id`),
  KEY `fk-appointment-service_id` (`service_id`),
  KEY `fk-appointment-source_id` (`source_id`),
  KEY `fk-appointment-type_service_accepted_id` (`type_service_accepted_id`),
  KEY `fk-appointment-type_service_id` (`type_service_id`),
  KEY `fk-appointment_appointment_type_id` (`appointment_type_id`),
  KEY `fk-appointment_branch_id` (`branch_id`),
  KEY `fk-appointment_created_by` (`created_by`),
  KEY `fk-appointment_is_accepted-app_is_accepted-id` (`is_accepted`),
  KEY `fk-appointment_updated_by` (`updated_by`),
  KEY `idx_appointment_created_scope` (`created_at`,`branch_id`,`appointment_type_id`,`source_id`,`customer_id`),
  KEY `idx_appointment_date_scope` (`appointment_date`,`status`,`branch_id`,`appointment_type_id`,`is_accepted`,`customer_id`,`type_service_accepted_id`,`source_id`),
  -- Màn danh sách lịch hẹn: ORDER BY appointment_date ASC, id DESC (tie-breaker tự thêm) đọc thẳng
  -- theo index, dừng sớm ở LIMIT. id DESC phải khai rõ — InnoDB tự gắn PK ASC vào cuối index phụ.
  -- Bench 1,2M dòng: trang tháng 834ms → 0,13ms. Đi cặp hint ở crm/appointment/handler (appointmentListPageHint).
  KEY `idx_appointment_date_id` (`appointment_date`,`id` DESC),
  KEY `idx_appointment_customer_date` (`customer_id`,`appointment_date`),
  KEY `idx_appointment_customer_status` (`customer_id`,`status`),
  KEY `idx_appointment_customer_type` (`customer_id`,`appointment_type_id`),
  CONSTRAINT `fk-appointment-appointment_reason_id` FOREIGN KEY (`appointment_reason_id`) REFERENCES `appointment_reason` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `fk-appointment-convert_id` FOREIGN KEY (`convert_id`) REFERENCES `user` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `fk-appointment-revenue_id` FOREIGN KEY (`revenue_id`) REFERENCES `user` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `fk-appointment-service_id` FOREIGN KEY (`service_id`) REFERENCES `service` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `fk-appointment-source_id` FOREIGN KEY (`source_id`) REFERENCES `source` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `fk-appointment-type_service_accepted_id` FOREIGN KEY (`type_service_accepted_id`) REFERENCES `service_type` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `fk-appointment-type_service_id` FOREIGN KEY (`type_service_id`) REFERENCES `service_type` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `fk-appointment_appointment_type_id` FOREIGN KEY (`appointment_type_id`) REFERENCES `appointment_type` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `fk-appointment_branch_id` FOREIGN KEY (`branch_id`) REFERENCES `branch` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `fk-appointment_customer_id` FOREIGN KEY (`customer_id`) REFERENCES `customer` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `fk-appointment_is_accepted-app_is_accepted-id` FOREIGN KEY (`is_accepted`) REFERENCES `appointment_is_accepted` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
