-- Tạo bảng `user_profile` (keep-set CRM). Idempotent: CREATE TABLE IF NOT EXISTS.
CREATE TABLE IF NOT EXISTS `user_profile` (
  `user_id` int NOT NULL AUTO_INCREMENT,
  `fullname` varchar(255) NOT NULL,
  `nickname` varchar(50) DEFAULT NULL COMMENT 'Bí danh nhân viên',
  `code` varchar(25) DEFAULT NULL,
  `birthday` date DEFAULT NULL,
  `about` text,
  `address` varchar(255) DEFAULT NULL,
  `phone` varchar(25) DEFAULT NULL,
  `email` varchar(255) DEFAULT NULL,
  `id_pancake` varchar(50) DEFAULT NULL,
  `facebook` varchar(255) DEFAULT NULL,
  `telegram` varchar(255) DEFAULT NULL,
  `avatar` varchar(255) DEFAULT NULL,
  `cover` varchar(255) DEFAULT NULL,
  `locale` varchar(32) DEFAULT 'vi-VN',
  `gender` smallint DEFAULT NULL,
  `departmentList` json DEFAULT NULL COMMENT 'Danh sách các phòng ban',
  `branchOffice_id` int DEFAULT NULL COMMENT 'Chi nhánh hoạt động',
  `branchActive_id` int DEFAULT NULL COMMENT 'Chi nhánh mà user muốn nhìn thấy khách hàng',
  `updated_at` bigint NOT NULL DEFAULT '0',
  PRIMARY KEY (`user_id`),
  UNIQUE KEY `email` (`email`),
  KEY `fk-user_profile-branchActive_id` (`branchActive_id`),
  KEY `fk-user_profile-branchOffice_id` (`branchOffice_id`),
  UNIQUE KEY `phone` (`phone`),
  CONSTRAINT `fk-user_profile-branchActive_id` FOREIGN KEY (`branchActive_id`) REFERENCES `branch` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `fk-user_profile-branchOffice_id` FOREIGN KEY (`branchOffice_id`) REFERENCES `branch` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `fk-user_profile-user_id` FOREIGN KEY (`user_id`) REFERENCES `user` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
