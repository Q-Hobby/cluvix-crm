-- Tạo bảng `location_country` (keep-set CRM). Idempotent: CREATE TABLE IF NOT EXISTS.
CREATE TABLE IF NOT EXISTS `location_country` (
  `id` int NOT NULL AUTO_INCREMENT,
  `CountryCode` varchar(255) DEFAULT NULL,
  `CommonName` varchar(255) DEFAULT NULL,
  `slug` varchar(255) DEFAULT NULL,
  `FormalName` varchar(255) DEFAULT NULL,
  `CountryType` varchar(255) DEFAULT NULL,
  `CountrySubType` varchar(255) DEFAULT NULL,
  `Sovereignty` varchar(255) DEFAULT NULL,
  `Capital` varchar(255) DEFAULT NULL,
  `CurrencyCode` varchar(255) DEFAULT NULL,
  `CurrencyName` varchar(255) DEFAULT NULL,
  `TelephoneCode` varchar(255) DEFAULT NULL,
  `CountryCode3` varchar(255) DEFAULT NULL,
  `CountryNumber` varchar(255) DEFAULT NULL,
  `InternetCountryCode` varchar(255) DEFAULT NULL,
  `SortOrder` int DEFAULT NULL,
  `status` tinyint(1) DEFAULT '1',
  `language` enum('vi','en','jp') NOT NULL DEFAULT 'vi' COMMENT 'Language',
  `Flags` varchar(255) DEFAULT NULL,
  `IsDeleted` tinyint(1) DEFAULT '0',
  `created_at` bigint DEFAULT NULL,
  `updated_at` bigint DEFAULT NULL,
  `created_by` int DEFAULT '1',
  `updated_by` int DEFAULT '1',
  PRIMARY KEY (`id`),
  KEY `fk_location_country_created_by_user` (`created_by`),
  KEY `fk_location_country_updated_by_user` (`updated_by`),
  KEY `index-language` (`language`),
  KEY `index-slug` (`slug`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
