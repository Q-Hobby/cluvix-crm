-- Tạo bảng `service` (keep-set CRM). Idempotent: CREATE TABLE IF NOT EXISTS.
CREATE TABLE IF NOT EXISTS `service` (
  `id` int NOT NULL AUTO_INCREMENT,
  `id_old` int DEFAULT NULL,
  `name` varchar(255) NOT NULL,
  `code` varchar(25) NOT NULL,
  `code_old` varchar(25) DEFAULT NULL COMMENT 'Mã dịch vụ cũ',
  `status` smallint DEFAULT '1',
  `SortOrder` int DEFAULT NULL COMMENT 'Vị trí hiển thị',
  `service_type_id` int DEFAULT NULL,
  `min_price` decimal(20,2) DEFAULT NULL COMMENT 'Giá dịch vụ thấp nhất',
  `max_price` decimal(20,2) DEFAULT NULL COMMENT 'Giá dịch vụ cao nhất',
  `unit_id` int DEFAULT NULL COMMENT 'Đơn vị tính của dịch vụ',
  `serviceCategory_id` int DEFAULT '1' COMMENT 'Dịch vụ hay sản phẩm',
  `child` tinyint(1) DEFAULT '0' COMMENT 'Thuộc răng trẻ em hay người lớn',
  `is_installment` tinyint(1) DEFAULT '0' COMMENT 'Dịch vụ được trả góp hay không?',
  `installment_config` json DEFAULT NULL COMMENT 'Cấu hình trả góp',
  `time_reminder` int DEFAULT '0' COMMENT 'Thời gian nhắc lịch hẹn sau khi sử dụng dịch vụ',
  `commission_telesale` decimal(20,2) DEFAULT '0.00' COMMENT 'Hoa hồng cho telesale đối với khách hàng cũ',
  `commission_telesale_new` decimal(20,2) DEFAULT '0.00' COMMENT 'Hoa hồng cho telesale đối với khách hàng mới',
  `commission_telesale_type` tinyint DEFAULT '1' COMMENT 'Loại hoa hồng cho telesale',
  `created_at` bigint DEFAULT NULL,
  `updated_at` bigint NOT NULL DEFAULT '0',
  `created_by` int DEFAULT NULL,
  `updated_by` int DEFAULT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `code` (`code`),
  KEY `fk-service-unit_id-unit-id` (`unit_id`),
  KEY `fk-service_created_by` (`created_by`),
  KEY `fk-service_service_type_id` (`service_type_id`),
  KEY `fk-service_updated_by` (`updated_by`),
  UNIQUE KEY `id_old` (`id_old`),
  CONSTRAINT `fk-service-unit_id-unit-id` FOREIGN KEY (`unit_id`) REFERENCES `unit` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `fk-service_service_type_id` FOREIGN KEY (`service_type_id`) REFERENCES `service_type` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
