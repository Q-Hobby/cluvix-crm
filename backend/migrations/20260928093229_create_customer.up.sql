-- Tạo bảng `customer` (keep-set CRM). Idempotent: CREATE TABLE IF NOT EXISTS.
CREATE TABLE IF NOT EXISTS `customer` (
  `id` int NOT NULL AUTO_INCREMENT,
  `id_old` int DEFAULT NULL COMMENT 'ID khách hàng cũ',
  `code` varchar(50) DEFAULT NULL COMMENT 'Mã khách hàng',
  `is_patient` tinyint(1) NOT NULL DEFAULT '0' COMMENT '0=Chưa là bệnh nhân, 1=Đã là bệnh nhân',
  `category` int DEFAULT NULL COMMENT 'Loại khách hàng',
  `old_code` varchar(50) DEFAULT NULL COMMENT 'Mã khách hàng cũ',
  `fullname` varchar(100) DEFAULT NULL,
  `nickname` varchar(100) DEFAULT NULL COMMENT 'Tên khác của khách hàng',
  `gender` tinyint(1) DEFAULT NULL,
  `tags` json DEFAULT NULL COMMENT 'Nhãn khách hàng',
  `job_id` int DEFAULT NULL COMMENT 'Nghề nghiệp',
  `ethnicity_id` int DEFAULT NULL COMMENT 'Dân tộc',
  `appointment_not_booked_reasons_id` int DEFAULT NULL COMMENT 'Lý do chưa ra hẹn lịch',
  `birthday` date DEFAULT NULL,
  `year_born` smallint DEFAULT NULL,
  `relatives` json DEFAULT NULL COMMENT 'Người thân',
  `phone` varchar(25) DEFAULT NULL,
  `avatar` varchar(500) DEFAULT NULL,
  `status` smallint NOT NULL DEFAULT '1' COMMENT 'Tiến trình',
  `facebook` varchar(255) DEFAULT NULL COMMENT 'Facebook người dùng',
  `instagram` varchar(255) DEFAULT NULL,
  `zalo` varchar(100) DEFAULT NULL,
  `email` varchar(100) DEFAULT NULL,
  `viber` varchar(100) DEFAULT NULL,
  `address` varchar(500) DEFAULT NULL,
  `address_other` varchar(500) DEFAULT NULL COMMENT 'Địa chỉ khác của khách hàng',
  `totalRevenue` decimal(20,2) DEFAULT '0.00' COMMENT 'Doanh số',
  `totalPayment` decimal(20,2) DEFAULT '0.00' COMMENT 'Doanh thu',
  `totalDebt` decimal(20,2) DEFAULT '0.00' COMMENT 'Công nợ',
  `totalDeposit` decimal(20,2) DEFAULT '0.00' COMMENT 'Đặt cọc',
  `totalBonus` decimal(20,2) DEFAULT '0.00' COMMENT 'Khuyến mại',
  `refundDeposit` decimal(20,2) DEFAULT '0.00' COMMENT 'Hoàn cọc',
  `refundService` decimal(20,2) DEFAULT '0.00' COMMENT 'Hoàn dịch vụ',
  `consignment` decimal(20,2) DEFAULT '0.00' COMMENT 'Ký gửi',
  `refundConsignment` decimal(20,2) DEFAULT '0.00' COMMENT 'Hoàn ký gửi',
  `customer_rank_id` int DEFAULT NULL COMMENT 'Hạng thành viên',
  `ward_id` int DEFAULT NULL,
  `province_id` int DEFAULT NULL,
  `country_id` int DEFAULT NULL,
  `branch_id` int DEFAULT NULL,
  `source_id` int DEFAULT NULL,
  `payment_user_id` int DEFAULT NULL COMMENT 'Doanh số khách hàng được tính cho ai',
  `salesStaff_id` int DEFAULT NULL COMMENT 'Nhân viên kinh doanh',
  `data_id` int DEFAULT NULL COMMENT 'Dữ liệu mới hay dữ liệu cũ',
  `connect_id` int DEFAULT '2' COMMENT 'Đã kết nối hay chưa, mặc định chưa kết nối',
  `customerType` int DEFAULT '1' COMMENT 'Khách hàng mới hay khách hàng cũ. Mặc định là khách hàng mới: 1',
  `other_phone` varchar(25) DEFAULT NULL COMMENT 'Số điện thoại khác',
  `loai_message` varchar(100) DEFAULT NULL COMMENT 'Loại message',
  `link_message` varchar(255) DEFAULT NULL COMMENT 'Link message',
  `chat_message` varchar(255) DEFAULT NULL COMMENT 'Chat message',
  `accepted` tinyint(1) DEFAULT '1' COMMENT 'Khách hàng đã đồng ý chưa?',
  `type_service_id` int DEFAULT NULL COMMENT 'Nhóm dịch vụ quan tâm',
  `created_day` bigint DEFAULT NULL,
  `last_contact_date` bigint DEFAULT NULL COMMENT 'Liên hệ lần cuối',
  `last_visit_date` bigint DEFAULT NULL COMMENT 'Lần ghé gần nhất',
  `created_at` bigint DEFAULT NULL,
  `updated_at` bigint NOT NULL DEFAULT '0',
  `created_by` int DEFAULT NULL,
  `updated_by` int DEFAULT NULL,
  `ma_dantoc` varchar(10) DEFAULT NULL COMMENT 'MA_DANTOC — mã dân tộc theo Bộ mã DMDC (XML BHXH)',
  `ma_nghe_nghiep` varchar(10) DEFAULT NULL COMMENT 'MA_NGHE_NGHIEP — mã nghề nghiệp theo Bộ mã DMDC (XML BHXH)',
  `search_ngram` varchar(720) GENERATED ALWAYS AS (concat_ws(_utf8mb4' ',nullif(`fullname`,_utf8mb4''),nullif(`code`,_utf8mb4''),nullif(`nickname`,_utf8mb4''),nullif(`phone`,_utf8mb4''),nullif(`other_phone`,_utf8mb4''),nullif(`old_code`,_utf8mb4''),nullif(`link_message`,_utf8mb4''),nullif(`loai_message`,_utf8mb4''))) STORED COMMENT 'Gộp 8 cột tìm kiếm cho chỉ mục ngram — xem migration 20260907081100',
  `phone_dup_legacy` tinyint NOT NULL DEFAULT '0' COMMENT '1 = trùng SĐT có từ trước UNIQUE SĐT (D-3) — miễn ràng buộc, cần gộp tay',
  `phone_unique_key` varchar(25) GENERATED ALWAYS AS (if((`phone_dup_legacy` = 1),NULL,nullif(right(regexp_replace(coalesce(`phone`,_utf8mb4''),_utf8mb4'[^0-9]',_utf8mb4''),9),_utf8mb4''))) VIRTUAL COMMENT 'Khoá UNIQUE SĐT: 9 số cuối (D-3)',
  PRIMARY KEY (`id`),
  KEY `fk-customer-appointment_not_booked_reasons_id` (`appointment_not_booked_reasons_id`),
  KEY `fk-customer-category-customer_category-id` (`category`),
  KEY `fk-customer-customer_rank_id` (`customer_rank_id`),
  KEY `fk-customer-ethnicity_id` (`ethnicity_id`),
  KEY `fk-customer-job_id` (`job_id`),
  KEY `fk-customer-payment_user_id` (`payment_user_id`),
  KEY `fk-customer-province_id` (`province_id`),
  KEY `fk-customer-salesStaff_id` (`salesStaff_id`),
  KEY `fk-customer-type_service_id` (`type_service_id`),
  KEY `fk-customer_branch_id` (`branch_id`),
  KEY `fk-customer_country_id` (`country_id`),
  KEY `fk-customer_created_by` (`created_by`),
  KEY `fk-customer_source_id` (`source_id`),
  KEY `fk-customer_updated_by` (`updated_by`),
  KEY `fk-customer_ward_id` (`ward_id`),
  FULLTEXT KEY `ft_customer_ngram` (`search_ngram`) /*!50100 WITH PARSER `ngram` */ ,
  UNIQUE KEY `id_old` (`id_old`),
  KEY `idx-customer-is_patient` (`is_patient`),
  KEY `idx_customer_branch_revenue` (`branch_id`,`totalRevenue`),
  KEY `idx_customer_created_day_branch` (`created_day`,`branch_id`),
  KEY `idx_customer_scope_status` (`status`,`branch_id`),
  KEY `idx_customer_total_debt` (`totalDebt`,`branch_id`,`totalRevenue`,`totalPayment`),
  KEY `index_phone_customer` (`phone`),
  UNIQUE KEY `uniq_customer_code` (`code`),
  UNIQUE KEY `uniq_customer_phone_key` (`phone_unique_key`),
  CONSTRAINT `fk-customer-appointment_not_booked_reasons_id` FOREIGN KEY (`appointment_not_booked_reasons_id`) REFERENCES `appointment_not_booked_reasons` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `fk-customer-category-customer_category-id` FOREIGN KEY (`category`) REFERENCES `customer_category` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `fk-customer-customer_rank_id` FOREIGN KEY (`customer_rank_id`) REFERENCES `customer_ranks` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `fk-customer-ethnicity_id` FOREIGN KEY (`ethnicity_id`) REFERENCES `ethnicity` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `fk-customer-job_id` FOREIGN KEY (`job_id`) REFERENCES `job` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `fk-customer-payment_user_id` FOREIGN KEY (`payment_user_id`) REFERENCES `user` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `fk-customer-province_id` FOREIGN KEY (`province_id`) REFERENCES `location_province` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `fk-customer-salesStaff_id` FOREIGN KEY (`salesStaff_id`) REFERENCES `user` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `fk-customer-type_service_id` FOREIGN KEY (`type_service_id`) REFERENCES `service_type` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `fk-customer_branch_id` FOREIGN KEY (`branch_id`) REFERENCES `branch` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `fk-customer_country_id` FOREIGN KEY (`country_id`) REFERENCES `location_country` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `fk-customer_source_id` FOREIGN KEY (`source_id`) REFERENCES `source` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `fk-customer_ward_id` FOREIGN KEY (`ward_id`) REFERENCES `location_ward` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
